"""Генератор світу гри ШАХТА-7.
Запуск: python3 tools/world.py  -> друкує JS-блок WORLD, який вставляється в index.html.
Легенда тайлів:
  #  стіна            .  порожньо          =  одностороння платформа / люк
  ^  шипи             x  тріснутий блок (ламається ривком-буром)
  b  синя броня (ламається зарядженим пострілом)
  %  фальшива стіна (можна пройти крізь неї)   L  ґрати арени боса
  S  станція (збереження, ремонт, магазин)
Предмети: D бур  M магнітні черевики  C заряджений постріл  J реактивний ранець
          H енергоблок (+1 макс. енергії)  W модуль гармати (+шкода)  R схованка брухту
Вороги:  c повзун  o стрибун  f літун  t турель  g щитоносець  d падальник
Боси:    B Сторож   Z Ядро
"""
import json, sys
CW, CH, COLS, ROWS = 30, 17, 10, 6          # клітинка мапи = 30x17 тайлів = 1 екран
W, H = CW*COLS, CH*ROWS
G = [['#']*W for _ in range(H)]
ROOMS = []

class Room:
    def __init__(s, key, name, region, cx, cy, cw, ch):
        s.key, s.name, s.region = key, name, region
        s.x0, s.y0, s.w, s.h = cx*CW, (cy+1)*CH, cw*CW, ch*CH
        s.cx, s.cy, s.cw, s.ch = cx, cy+1, cw, ch
        ROOMS.append(s)
        s.f(1, 1, s.w-2, s.h-2, '.')
    def f(s, x0, y0, x1, y1, c):
        for y in range(y0, y1+1):
            for x in range(x0, x1+1):
                assert 0 <= x < s.w and 0 <= y < s.h, (s.key, x, y)
                G[s.y0+y][s.x0+x] = c
    def p(s, x, y, c): s.f(x, y, x, y, c)
    def door(s, side, a, b, mine='.', theirs='.'):
        for i in range(a, b+1):
            if side == 'r': G[s.y0+i][s.x0+s.w-1] = mine; G[s.y0+i][s.x0+s.w] = theirs
            if side == 'l': G[s.y0+i][s.x0] = mine;       G[s.y0+i][s.x0-1] = theirs
            if side == 'd': G[s.y0+s.h-1][s.x0+i] = mine; G[s.y0+s.h][s.x0+i] = theirs
            if side == 'u': G[s.y0][s.x0+i] = mine;       G[s.y0-1][s.x0+i] = theirs

